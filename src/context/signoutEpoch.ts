// ============================================================================
// 登出标记：一个**跨整页导航、跨标签页**都还在的「有人登出过」印记
//
// ── 它解决的是什么 ──────────────────────────────────────────────────────────
// 统一身份的二次验证是**整页跳转**出去再回来的。跳出去期间用户在别的标签页点了
// 「退出登录」，回来时那笔挑战仍然有效 —— 后端照样验证通过、照样建会话、照样写 cookie。
// 于是「用户明确执行的登出」被一个登出之前发起、尚未完成的流程**撤销**了，人又被登了回去。
//
// 页面内存里的身份代次（api/client 的 _identityGen）拦不住它：整页跳转之后进程都换了，
// 代次从 0 重新开始。而「此刻是谁」也拦不住 —— 登出之后浏览器是 anonymous，
// 「没有人」和「还没登录」长得一模一样。
//
// 所以需要一个**持久**的印记：登出时换一个新值，发起外跳的流程把当时的值抄进交接数据，
// 回来一比 —— 变了就说明这中间有人登出过，这笔挑战属于那之前，不能再完成。
//
// 用 localStorage 而不是 sessionStorage：登出可能发生在**另一个**标签页，
// sessionStorage 是标签页级的，看不见。
//
// ⚠️ 这是**一致性**机制，不是安全机制：它只防「自己人晚到一步」。
//
// 已知的退化：localStorage 不可用（隐私模式、配额满、被策略禁用）时读写都会失败，
// 这道保护静默失效 —— 那时仍有 `priorUserId`（挡「回来时是另一个人」）
// 与 `status` 那两道判断，但「登出之后被旧流程登回去」这一幕拦不住。
// 要消灭它需要服务端可校验的登出边界（例如把登出时刻记进会话、让挑战完成时比对），
// 当前判断是代价大于收益。真正的凭据校验始终在后端。
// ============================================================================

const KEY = "pass_signout_epoch";

/**
 * 读当前登出标记。读不到（首次、隐私模式、被清）一律当 `null`。
 *
 * 调用方只该拿它做**相等比较**（「和我出发时记的那个还是同一个吗」），
 * 不要假设它有序或可比大小 —— 它是个随机值，不是计数器，理由见 `markSignedOut()`。
 */
export function readSignoutEpoch(): string | null {
  try {
    return localStorage.getItem(KEY);
  } catch {
    return null;
  }
}

/**
 * 记下「有人登出过」。**只在确实有一个身份被终结时调用**。
 *
 * 「探测没问出结果」不算 —— 那时什么都没发生，动它会把一笔正在外跳的合法流程白白作废。
 *
 * **写的是随机值，不是 +1。** 递增要先读再写，而 localStorage 没有原子的读-改-写：
 * 两个标签页同时登出会交错成「A 读 E、B 读 E、A 写 E+1、B 写 E+1」——
 * B 那次登出被覆盖掉了，中间记下 E+1 的那笔外跳流程回来一比「没变」，于是照常登录，
 * 而用户明明登出过两次。随机值没有这个问题：**谁写的都算数**，
 * 只要写过，先前记下的那个值就不可能再相等。
 */
export function markSignedOut(): void {
  try {
    localStorage.setItem(KEY, newMark());
  } catch {
    /* 配额满 / 隐私模式：退化为不拦，见文件头 */
  }
}

function newMark(): string {
  try {
    if (typeof crypto !== "undefined" && typeof crypto.randomUUID === "function") {
      return crypto.randomUUID();
    }
  } catch {
    /* 落到下面的退路 */
  }
  return `${Date.now().toString(36)}-${Math.random().toString(36).slice(2)}`;
}
